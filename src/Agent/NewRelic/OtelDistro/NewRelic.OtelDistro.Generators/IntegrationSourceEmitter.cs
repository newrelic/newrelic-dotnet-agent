using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;
using static NewRelic.Agent.Core.OtelDistro.InstrumentationDefinitionsTableFormat;

namespace NewRelic.OtelDistro.Generators;

/// <summary>
/// Turns parsed instrumentation points into the generated CallTarget integration source: one abstract class per
/// point (named by its function id) plus a single <c>GeneratedDistroDefinitions</c> class whose <c>Table</c> holds every
/// resulting CallTarget definition as an NRIDT table (see <see cref="InstrumentationDefinitionsTableWriter"/>).
/// </summary>
public static class IntegrationSourceEmitter
{
    public const int MaxParameters = XmlPointEligibility.MaxParameters;

    private const char LineSeparator = (char)0x2028;
    private const char ParagraphSeparator = (char)0x2029;

    private static readonly ShippedXmlFile[] NoFiles = new ShippedXmlFile[0];

    /// <summary>
    /// Emits the source for <paramref name="points"/>, all from the plugin's own XML, with no shipped XML manifest.
    /// See the other overload.
    /// </summary>
    public static bool TryEmit(IReadOnlyList<XmlInstrumentationPoint> points, string generatedNamespace, out string source, out string failureReason) =>
        TryEmit(points.Select(p => new SourcedXmlPoint(p, SourcedXmlPoint.PluginSourceFile)).ToList(), NoFiles, generatedNamespace, out source, out failureReason);

    /// <summary>
    /// Emits the source for <paramref name="points"/> and the shipped XML manifest <paramref name="files"/> (a point's
    /// SourceFile indexes into it). Every record of a point carries the point's key (PointKeyHasher), its source file
    /// and whether it is default-off (enabled="false" in the XML). Returns false, with a null <paramref name="source"/>
    /// and the writer's <paramref name="failureReason"/>, when the definitions cannot be written as a table (a format
    /// limit).
    /// </summary>
    /// <remarks>
    /// The table is written before any class is emitted: the writer sorts records by assembly, so a class's
    /// <c>SiteIndex</c> (its record's index, which is where the plugin finds its site at run time) is only known then.
    /// </remarks>
    public static bool TryEmit(IReadOnlyList<SourcedXmlPoint> points, IReadOnlyList<ShippedXmlFile> files, string generatedNamespace, out string source, out string failureReason) =>
        TryEmit(points, files, generatedNamespace, DistroTargetRuntime.NetFramework, out source, out failureReason);

    /// <summary>
    /// As the overload above, with the OTel disable list and exclude additions resolved for <paramref name="runtime"/>
    /// (see <see cref="OtelInstrumentationMap"/>); the overload above uses the .NET Framework rules.
    /// </summary>
    public static bool TryEmit(IReadOnlyList<SourcedXmlPoint> points, IReadOnlyList<ShippedXmlFile> files, string generatedNamespace, DistroTargetRuntime runtime, out string source, out string failureReason)
    {
        var integrations = new List<Integration>();

        // Only points that produce table entries may turn OTel instrumentation off: a dropped point (more than
        // MaxParameters parameters) leaves NR with nothing there, so OTel must keep instrumenting that library. Nor may a
        // default-off point: NR does not instrument there unless someone turns it on, so OTel keeps the library.
        var defaultOnEmittedPoints = new List<XmlInstrumentationPoint>();

        foreach (var sourced in points.Where(p => p.Point.ParameterTypes != null && p.Point.ParameterTypes.Count <= MaxParameters))
        {
            integrations.Add(ExplicitIntegration(sourced, generatedNamespace));
            AddIfDefaultOn(defaultOnEmittedPoints, sourced.Point);
        }

        foreach (var sourced in points.Where(p => p.Point.ParameterTypes == null))
        {
            AddIfDefaultOn(defaultOnEmittedPoints, sourced.Point);
            for (var arity = 0; arity <= MaxParameters; arity++)
            {
                integrations.Add(OverloadWideIntegration(sourced, arity, generatedNamespace));
            }
        }

        if (!InstrumentationDefinitionsTableWriter.TryWrite(integrations.Select(i => i.Entry).ToList(), files, out var table, out var recordIndexOfEntry, out failureReason))
        {
            source = null;
            return false;
        }

        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        // The emitted integration classes are public (upstream resolves them by name) but intentionally carry no XML
        // doc comments; suppress CS1591 so a consuming project with documentation-file warnings-as-errors still builds.
        builder.AppendLine("#pragma warning disable CS1591");
        builder.AppendLine("using System;");
        builder.AppendLine("using NewRelic.OtelDistro.Plugin;");
        builder.AppendLine("using OpenTelemetry.AutoInstrumentation.CallTarget;");
        builder.AppendLine();
        builder.AppendLine($"namespace {generatedNamespace};");
        builder.AppendLine();

        for (var i = 0; i < integrations.Count; i++)
        {
            EmitIntegrationClass(builder, integrations[i], recordIndexOfEntry[i]);
        }

        var (disableIds, excludeSources) = OtelInstrumentationMap.Resolve(defaultOnEmittedPoints.Select(p => p.AssemblyName), runtime);

        // Whether NR's NLog log-forwarding wrapper is compiled default-on. OTel's NLog bridge cannot be deduped per call
        // (it emits in the OnMethodBegin of the outer NLog.Logger.WriteToTargets, before NR's inner LoggerImpl.Write hook),
        // so the plugin uses this flag only to diagnose (warn) when the customer has OTel's opt-in NLog bridge on at the
        // same time -- it does not write the bridge setting. log4net and ILogger bridges emit synchronously inside NR's
        // hook, so the per-call dedupe covers them.
        var nrCompilesNLogLogForwarding = defaultOnEmittedPoints.Any(p => LogForwardingClassification.IsNLog(p.TracerFactoryName));
        EmitDefinitionsTable(builder, table, runtime, disableIds, excludeSources, nrCompilesNLogLogForwarding);
        source = builder.ToString();
        return true;
    }

    /// <summary>
    /// Emits the table as a byte[] literal, which compiles to one allocation plus a memory copy at start-up (instead of
    /// a static constructor that builds every definition). 16 bytes per line; the comment above it gives the counts.
    /// </summary>
    private static void EmitDefinitionsTable(StringBuilder builder, byte[] table, DistroTargetRuntime runtime, IReadOnlyList<string> disableIds, IReadOnlyList<string> excludeSources, bool nrCompilesNLogLogForwarding)
    {
        builder.AppendLine("public static class GeneratedDistroDefinitions");
        builder.AppendLine("{");
        builder.AppendLine(string.Format(
            CultureInfo.InvariantCulture,
            "    // NRIDT instrumentation definitions table, format version {0}: {1} strings, {2} signatures, {3} records, {4} assemblies, {5} files, {6} bytes.",
            FormatVersion,
            ReadHeaderU32(table, HeaderStringCount),
            ReadHeaderU32(table, HeaderSignatureCount),
            ReadHeaderU32(table, HeaderRecordCount),
            ReadHeaderU32(table, HeaderAssemblyCount),
            ReadHeaderU32(table, HeaderFileCount),
            table.Length));
        builder.AppendLine("    // Read once per AppDomain (at start-up, or on the first instrumented call in another AppDomain) by");
        builder.AppendLine("    // NewRelic.Agent.Core.OtelDistro.InstrumentationDefinitionsTable. Layout, validity rules and the");
        builder.AppendLine("    // reasons for both: src/Agent/NewRelic/Agent/Core/OtelDistro/InstrumentationDefinitionsTableFormat.cs");
        builder.AppendLine("    public static readonly byte[] Table = new byte[]");
        builder.AppendLine("    {");
        for (var i = 0; i < table.Length; i++)
        {
            var startsLine = i % 16 == 0;
            var endsLine = i % 16 == 15 || i == table.Length - 1;
            builder.Append(startsLine ? "        " : " ");
            builder.Append("0x").Append(table[i].ToString("X2", CultureInfo.InvariantCulture)).Append(',');
            if (endsLine)
            {
                builder.AppendLine();
            }
        }
        builder.AppendLine("    };");
        builder.AppendLine();
        builder.AppendLine("    // OTel trace instrumentation IDs to disable (OTEL_DOTNET_AUTO_TRACES_<ID>_INSTRUMENTATION_ENABLED=false), derived from");
        builder.AppendLine($"    // the default-on NR XML points in the table by OtelInstrumentationMap (built for OTel {OtelInstrumentationMap.OtelVersion}), {runtime} rules. Sorted, distinct.");
        EmitStringArray(builder, "DisabledOtelTraceInstrumentationIds", disableIds);
        builder.AppendLine();
        builder.AppendLine("    // ActivitySource names to add to the distro's default-exclude list, from the same map. Sorted, distinct.");
        EmitStringArray(builder, "ExcludedActivitySourceAdditions", excludeSources);
        builder.AppendLine();
        builder.AppendLine("    // True when NR's NLog log-forwarding wrapper is compiled default-on. The plugin uses this only to diagnose");
        builder.AppendLine("    // (warn) when the customer also has OTel's opt-in NLog bridge on: OTel's NLog bridge emits before NR's inner");
        builder.AppendLine("    // hook, so the per-call log dedupe cannot catch it and NLog lines may be forwarded twice. The plugin does NOT");
        builder.AppendLine("    // write the bridge setting. const so reading it triggers no generated-type initializer.");
        builder.AppendLine($"    public const bool NrCompilesNLogLogForwarding = {(nrCompilesNLogLogForwarding ? "true" : "false")};");
        builder.AppendLine("}");
    }

    private static void EmitStringArray(StringBuilder builder, string fieldName, IReadOnlyList<string> values)
    {
        if (values.Count == 0)
        {
            builder.AppendLine($"    public static readonly string[] {fieldName} = new string[0];");
            return;
        }

        builder.AppendLine($"    public static readonly string[] {fieldName} = new string[]");
        builder.AppendLine("    {");
        foreach (var value in values)
        {
            builder.AppendLine($"        \"{value}\",");
        }

        builder.AppendLine("    };");
    }

    private static void AddIfDefaultOn(List<XmlInstrumentationPoint> defaultOnPoints, XmlInstrumentationPoint point)
    {
        if (point.Enabled)
        {
            defaultOnPoints.Add(point);
        }
    }

    private static uint ReadHeaderU32(byte[] table, int position) =>
        (uint)(table[position] | (table[position + 1] << 8) | (table[position + 2] << 16) | (table[position + 3] << 24));

    private static Integration ExplicitIntegration(SourcedXmlPoint sourced, string generatedNamespace)
    {
        var point = sourced.Point;
        var argumentSignature = string.Join(",", point.ParameterTypes);
        var range = VersionRangeConverter.Convert(point.MinVersion, point.MaxVersion);
        var functionId = FunctionIdHasher.Compute(point.AssemblyName, point.ClassName, point.MethodName, argumentSignature, FunctionIdRangeKey(sourced, range));
        var className = ClassName(functionId);
        var signature = new[] { "_" }.Concat(point.ParameterTypes).ToArray();
        var entry = NewEntry(sourced, signature, generatedNamespace + "." + className, argumentSignature, functionId, range);
        return new Integration(entry, className, point.ParameterTypes.Count, argumentSignature);
    }

    /// <summary>
    /// One integration for a match with no <c>parameters</c> attribute, for a single arity. The native profiler treats a
    /// missing <c>parameters</c> as "all overloads"; upstream OTel's matcher only compares argument count plus types
    /// (with <c>"_"</c> matching any type), so overload-wide matching has to be expressed as one definition per arity
    /// (0..<see cref="MaxParameters"/>).
    /// </summary>
    private static Integration OverloadWideIntegration(SourcedXmlPoint sourced, int arity, string generatedNamespace)
    {
        var point = sourced.Point;
        var range = VersionRangeConverter.Convert(point.MinVersion, point.MaxVersion);
        var functionId = FunctionIdHasher.Compute(point.AssemblyName, point.ClassName, point.MethodName, "*" + arity.ToString(CultureInfo.InvariantCulture), FunctionIdRangeKey(sourced, range));
        var className = ClassName(functionId);
        var signature = Enumerable.Repeat("_", arity + 1).ToArray();
        var entry = NewEntry(sourced, signature, generatedNamespace + "." + className, "", functionId, range);
        return new Integration(entry, className, arity, "any " + arity.ToString(CultureInfo.InvariantCulture) + " parameters");
    }

    /// <summary>
    /// The table entry for one integration, carrying the point's version range as OTel's inclusive three-part bounds
    /// (the default 0.0.0 to 65535.65535.65535 when the XML gives none), plus the point's key, source file and default-off
    /// flag. Every entry of one point (all nine of an overload-wide one) gets the same key. The generator drops points
    /// whose range is empty before they get here.
    /// </summary>
    private static TableEntry NewEntry(SourcedXmlPoint sourced, string[] signature, string integrationType, string argumentSignature, ulong functionId, VersionRangeConversion range)
    {
        var point = sourced.Point;
        var flags = (point.Enabled ? TableEntryFlags.None : TableEntryFlags.DefaultOff)
            | (LogForwardingClassification.IsLogForwarding(point.TracerFactoryName) ? TableEntryFlags.LogForwarding : TableEntryFlags.None);
        return new TableEntry(
            point.AssemblyName, point.ClassName, point.MethodName, signature, integrationType, point.TracerFactoryName, point.MetricName, argumentSignature, 0, functionId,
            range.MinMajor, range.MinMinor, range.MinPatch, range.MaxMajor, range.MaxMinor, range.MaxPatch,
            PointKeyHasher.Compute(point, point.ClassName, range.RangeKey), sourced.SourceFile, flags);
    }

    /// <summary>
    /// The range key the function id is hashed with: the point's own, plus <c>"|" + tracer factory</c> for a point that
    /// <see cref="SourcedXmlPoint.DistinguishByTracerFactory"/> (so a same-method point of another factory gets its own
    /// class). Only the hash input changes; the record's version range stays the point's.
    /// </summary>
    private static string FunctionIdRangeKey(SourcedXmlPoint sourced, VersionRangeConversion range) =>
        sourced.DistinguishByTracerFactory
            ? range.RangeKey + "|" + (sourced.Point.TracerFactoryName ?? InstrumentationXmlParser.DefaultTracerFactoryName)
            : range.RangeKey;

    private static string ClassName(ulong functionId) => "NrDistroIntegration_" + functionId.ToString("X16", CultureInfo.InvariantCulture);

    /// <summary>
    /// One integration class. It holds no site data, only <c>SiteIndex</c>: the index of its record in the table, which
    /// is where the plugin finds its site at run time. The comment line above it names the target so the generated file
    /// stays readable.
    /// </summary>
    private static void EmitIntegrationClass(StringBuilder builder, Integration integration, int siteIndex)
    {
        var entry = integration.Entry;
        builder.AppendLine($"// {OneLine(entry.Assembly)} / {OneLine(entry.Type)}.{OneLine(entry.Method)}({OneLine(integration.TargetDescription)})");
        // Abstract rather than static: OnMethodBegin passes the class as a type argument to DistroCallTarget.Begin, and a
        // static class cannot be one. Everything in it is static and nothing can instantiate it, as before. Safe because
        // OTel looks up OnMethodBegin/OnMethodEnd only with BindingFlags.Static, never by whether the class is static.
        builder.AppendLine($"public abstract class {integration.ClassName}");
        builder.AppendLine("{");
        builder.AppendLine($"    public const int SiteIndex = {siteIndex.ToString(CultureInfo.InvariantCulture)};");
        builder.AppendLine();

        EmitOnMethodBegin(builder, integration.ClassName, integration.ParameterCount);
        EmitOnMethodEnd(builder);
    }

    /// <summary>
    /// Emits <c>OnMethodBegin</c>, which hands the plugin the integration class itself as the first type argument. The
    /// plugin keeps one cached method resolution per instantiation of that generic call, so each distinct overload OTel
    /// passes (its type arguments are the real argument types) is resolved once, then read from that instantiation's cached static field (no lock, reflection
    /// or allocation).
    /// </summary>
    private static void EmitOnMethodBegin(StringBuilder builder, string className, int parameterCount)
    {
        if (parameterCount == 0)
        {
            builder.AppendLine("    public static CallTargetState OnMethodBegin<TTarget>(TTarget instance)");
            builder.AppendLine($"        => DistroCallTarget.Begin<{className}, TTarget>(SiteIndex, instance);");
            return;
        }

        var typeParams = string.Join(", ", Enumerable.Range(1, parameterCount).Select(i => "TArg" + i));
        var methodParams = string.Join(", ", Enumerable.Range(1, parameterCount).Select(i => "ref TArg" + i + " arg" + i));
        var argRefs = string.Join(", ", Enumerable.Range(1, parameterCount).Select(i => "arg" + i));

        builder.AppendLine($"    public static CallTargetState OnMethodBegin<TTarget, {typeParams}>(TTarget instance, {methodParams})");
        builder.AppendLine($"        => DistroCallTarget.Begin<{className}, TTarget, {typeParams}>(SiteIndex, instance, {argRefs});");
    }

    /// <summary>
    /// Emits the two <c>OnMethodEnd</c> overloads (void and non-void target methods) plus the closing class
    /// brace and a trailing blank line. Identical for every integration class regardless of arity or whether the
    /// match came from an explicit <c>parameters</c> attribute or an overload-wide expansion.
    /// </summary>
    private static void EmitOnMethodEnd(StringBuilder builder)
    {
        builder.AppendLine();
        builder.AppendLine("    public static CallTargetReturn OnMethodEnd<TTarget>(TTarget instance, Exception exception, in CallTargetState state)");
        builder.AppendLine("    {");
        builder.AppendLine("        DistroCallTarget.End(in state, exception);");
        builder.AppendLine("        return CallTargetReturn.GetDefault();");
        builder.AppendLine("    }");
        builder.AppendLine();
        builder.AppendLine("    public static CallTargetReturn<TReturn> OnMethodEnd<TTarget, TReturn>(TTarget instance, TReturn returnValue, Exception exception, in CallTargetState state)");
        builder.AppendLine("    {");
        builder.AppendLine("        DistroCallTarget.End<TReturn>(in state, returnValue, exception);");
        builder.AppendLine("        return new CallTargetReturn<TReturn>(returnValue);");
        builder.AppendLine("    }");
        builder.AppendLine("}");
        builder.AppendLine();
    }

    // XML attribute values may carry line breaks (&#10;). A control character or a Unicode line or paragraph separator
    // would end the // comment early and break the build, so each one becomes a space.
    private static string OneLine(string value)
    {
        var chars = value.ToCharArray();
        for (var i = 0; i < chars.Length; i++)
        {
            if (char.IsControl(chars[i]) || chars[i] == LineSeparator || chars[i] == ParagraphSeparator)
            {
                chars[i] = ' ';
            }
        }

        return new string(chars);
    }

    /// <summary>One integration class to emit: its table entry, class name, arity and the comment's target text.</summary>
    private sealed class Integration
    {
        public TableEntry Entry { get; }

        public string ClassName { get; }

        public int ParameterCount { get; }

        /// <summary>The comma-joined parameter types, or "any N parameters" for one arity of an overload-wide match.</summary>
        public string TargetDescription { get; }

        public Integration(TableEntry entry, string className, int parameterCount, string targetDescription)
        {
            Entry = entry;
            ClassName = className;
            ParameterCount = parameterCount;
            TargetDescription = targetDescription;
        }
    }
}
